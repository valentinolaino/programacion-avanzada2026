// Función que Multiplica:
//○ Crea una función llamada multiplicar que tome dos números como
//parámetros y devuelva su producto. Prueba la función con diferentes valores.

const multiplicar = (numero1, numero2) => {
    return numero1 * numero2;
};

console.log(`Resultado de multiplicar dos números: ${multiplicar(5, 3)}`);
console.log(`Resultado de multiplicar dos números: ${multiplicar(10, 20)}`);
console.log(`Resultado de multiplicar dos números: ${multiplicar(50, 100)}`);
