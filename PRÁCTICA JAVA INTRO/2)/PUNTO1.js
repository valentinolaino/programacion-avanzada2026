// Función Suma:
//○ Crea una función llamada sumar que tome dos números como
//parámetros y devuelva su suma. Prueba la función con diferentes números.

const sumar = (numero1, numero2) => {
    return numero1 + numero2;
};

console.log(`Resultado de sumar dos números: ${sumar(5, 3)}`);
console.log(`Resultado de sumar dos números: ${sumar(10, 20)}`);
console.log(`Resultado de sumar dos números: ${sumar(50, 100)}`);
